const crypto = require('crypto');
const Tesseract = require('tesseract.js');
const pdf = require('pdf-parse');
const { linkCandidateAuditLog, linkCandidateSkill } = require('../db/neo4j');
const { callGeminiWithTelemetry } = require('../services/tokenTelemetry');

/**
 * Computes deterministic SHA-256 hash of text/buffer.
 */
function computeSha256(data) {
  const buffer = Buffer.isBuffer(data) ? data : Buffer.from(String(data), 'utf8');
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

/**
 * Extracts raw text from image using Tesseract OCR.
 */
async function extractTextFromImage(imageBufferOrPath) {
  try {
    const { data: { text } } = await Tesseract.recognize(imageBufferOrPath, 'eng');
    return text || '';
  } catch (error) {
    console.warn('[Agent1 Ingestion] OCR error:', error.message);
    return '';
  }
}

/**
 * Extracts raw text from PDF buffer.
 */
async function extractTextFromPdf(pdfBuffer) {
  try {
    const data = await pdf(pdfBuffer);
    return data.text || '';
  } catch (error) {
    console.warn('[Agent1 Ingestion] PDF parse error:', error.message);
    return '';
  }
}

/**
 * Classifies if the text is AI-generated (ChatGPT/synthetic) using Gemini with Telemetry.
 */
async function classifySyntheticText(text, sessionId = 'agent1-ingest') {
  if (!text || text.trim().length === 0) {
    return { isSynthetic: false, confidence: 0, reason: 'Empty text' };
  }

  const prompt = `
You are an advanced AI forensic text detector. Analyze the following resume/document text and determine the probability (0.0 to 1.0) that it was synthetically generated by an LLM (such as ChatGPT, Claude, etc.) vs authentic human writing.
Look for typical AI resume hallmarks (overused buzzwords like "spearheaded", generic metrics, robotic sentence structures, lack of concrete technical nuance).

Document snippet:
"""
${text.slice(0, 3000)}
"""

Return strictly a valid JSON object with the following schema:
{
  "isSynthetic": boolean,
  "confidence": number, // float 0.0 to 1.0
  "reason": string
}
`;

  return await callGeminiWithTelemetry({
    sessionId,
    contents: prompt,
    config: { responseMimeType: 'application/json' },
    fallbackFn: () => {
      // Heuristic fallback for offline/test environments
      const lower = text.toLowerCase();
      const aiBuzzwords = ['spearheaded', 'leveraged', 'orchestrated', 'synergy', 'transformative', 'cutting-edge'];
      let matchCount = 0;
      aiBuzzwords.forEach(bw => { if (lower.includes(bw)) matchCount++; });
      const conf = Math.min(matchCount * 0.15, 0.85);
      return {
        isSynthetic: conf > 0.6,
        confidence: conf,
        reason: 'Heuristic keyword density scan (offline fallback)'
      };
    }
  }).then(res => {
    if (res.text) {
      try {
        return JSON.parse(res.text);
      } catch (e) {
        return { isSynthetic: false, confidence: 0.2, reason: 'Parse fallback' };
      }
    }
    return res;
  });
}

/**
 * Parses candidate profile structure from text using Gemini.
 */
async function parseCandidateProfile(text, sessionId = 'agent1-ingest') {
  const prompt = `
Extract the candidate profile information from this resume text:
"""
${text.slice(0, 4000)}
"""

Return strictly a valid JSON object with:
{
  "name": string,
  "email": string,
  "phone": string,
  "skills": [{"name": string, "category": string, "level": string}],
  "experienceYears": number,
  "summary": string
}
`;

  return await callGeminiWithTelemetry({
    sessionId,
    contents: prompt,
    config: { responseMimeType: 'application/json' },
    fallbackFn: () => {
      // Offline fallback extraction
      const emailMatch = text.match(/[\w.-]+@[\w.-]+\.\w+/);
      return {
        name: 'Extracted Candidate',
        email: emailMatch ? emailMatch[0] : `candidate_${Date.now()}@talentos.io`,
        phone: '',
        skills: [{ name: 'JavaScript', category: 'Programming', level: 'Intermediate' }],
        experienceYears: 2,
        summary: text.slice(0, 200)
      };
    }
  }).then(res => {
    if (res.text) {
      try { return JSON.parse(res.text); } catch (e) { /* use default */ }
    }
    return res;
  });
}

/**
 * Main Agent 1 Ingestion Workflow:
 * OCR/PDF Extraction -> SHA-256 Hashing -> Synthetic Text Classification -> Profile Generation & Graph Ingestion.
 */
async function processCandidateIngestion({ fileBuffer, mimeType, rawText, candidateEmail = null, sessionId = 'agent1-session' }) {
  let extractedText = rawText || '';

  if (fileBuffer) {
    if (mimeType === 'application/pdf') {
      extractedText = await extractTextFromPdf(fileBuffer);
    } else if (mimeType && mimeType.startsWith('image/')) {
      extractedText = await extractTextFromImage(fileBuffer);
    }
  }

  const sha256 = computeSha256(extractedText || fileBuffer || Date.now().toString());
  const syntheticAudit = await classifySyntheticText(extractedText, sessionId);
  const profile = await parseCandidateProfile(extractedText, sessionId);

  if (candidateEmail) {
    profile.email = candidateEmail;
  }

  const fraudFlag = syntheticAudit.isSynthetic && syntheticAudit.confidence >= 0.70;

  // Ingest audit log and links into Neo4j
  await linkCandidateAuditLog(profile.email, {
    sha256,
    fraudFlag,
    syntheticConfidence: syntheticAudit.confidence,
    extractedTextLength: extractedText.length
  });

  if (profile.skills && Array.isArray(profile.skills)) {
    for (const s of profile.skills) {
      await linkCandidateSkill({ email: profile.email, name: profile.name }, s);
    }
  }

  return {
    profile,
    sha256,
    syntheticAudit,
    fraudFlag,
    extractedTextLength: extractedText.length
  };
}

module.exports = {
  computeSha256,
  extractTextFromImage,
  extractTextFromPdf,
  classifySyntheticText,
  parseCandidateProfile,
  processCandidateIngestion
};
